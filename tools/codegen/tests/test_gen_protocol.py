# tools/codegen is on sys.path through conftest.py.
ROOT = Path(__file__).resolve().parents[3]

# Any: the tests edit arbitrary nested schema nodes.
SCHEMA: Any = json.loads((ROOT / gen_protocol.SCHEMA).read_text(encoding="utf-8"))
README = (ROOT / gen_protocol.README).read_text(encoding="utf-8")
COMMITTED = ROOT / gen_protocol.OUTPUT
Mutation = Callable[[Any], None]


def _defs(schema: Any) -> Any:
    return schema["$defs"]


def _body(schema: Any, name: str) -> Any:
    return schema["$defs"][f"body.{name}"]


def _blocks(schema: Any) -> Any:
    return schema["allOf"]


def _error(mutate: Mutation, readme: str = README) -> str:
    schema = copy.deepcopy(SCHEMA)
    mutate(schema)
    with pytest.raises(CodegenError) as caught:
        build_model(schema, readme)
    return str(caught.value)


def _load_generated() -> ModuleType:
    spec = importlib.util.spec_from_file_location("protocol_types_under_test", COMMITTED)
    assert spec is not None and spec.loader is not None
    module = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(module)
    return module


# --- the real schema -------------------------------------------------------------------------------------------------


def test_every_type_has_exactly_one_body_definition() -> None:
    model = build_model(SCHEMA, README)
    enum = SCHEMA["properties"]["type"]["enum"]
    body_defs = sorted(name[5:] for name in _defs(SCHEMA) if name.startswith("body."))
    assert list(model.frame_types) == enum
    assert sorted(frame.type_name for frame in model.frames) == body_defs == sorted(enum)
    struct_names = [struct.name for struct in model.structs]
    assert len(struct_names) == len(set(struct_names))
    assert all(frame.body in struct_names for frame in model.frames)


def test_seq_rules_and_directions_follow_schema_and_readme() -> None:
    frames = {frame.type_name: frame for frame in build_model(SCHEMA, README).frames}
    assert (frames["welcome"].seq, frames["welcome"].direction) == ("required", "S→D")
    assert (frames["hello"].seq, frames["hello"].direction) == ("absent", "D→S")
    assert (frames["ping"].seq, frames["ping"].direction) == ("absent", "both")
    assert (frames["error"].seq, frames["error"].direction) == ("optional", "both")


def test_committed_module_is_fresh() -> None:
    assert gen_protocol.generate(ROOT) == COMMITTED.read_text(encoding="utf-8")


def test_generator_owns_every_committed_file_of_the_directory() -> None:
    committed = {p.name: p.read_text(encoding="utf-8") for p in (ROOT / gen_protocol.OUTPUT_DIR).glob("*.py")}
    assert gen_protocol.generate_dir(ROOT) == committed


def test_header_carries_spdx_and_generated_marker() -> None:
    head = COMMITTED.read_text(encoding="utf-8").splitlines()[:2]
    assert head[0] == "# SPDX-License-Identifier: Apache-2.0"
    assert head[1].startswith("# @generated by tools/codegen/gen_protocol.py")


def test_generated_module_imports_and_matches_schema() -> None:
    module = _load_generated()
    assert module.FRAME_TYPES == typing.get_args(module.FrameType) == tuple(SCHEMA["properties"]["type"]["enum"])
    assert {"hello", "ping", "error"} <= module.DEVICE_TO_SERVER
    assert {"welcome", "ping", "error"} <= module.SERVER_TO_DEVICE
    assert "welcome" not in module.DEVICE_TO_SERVER and "hello" not in module.SERVER_TO_DEVICE
    assert module.MsgOutBody.__optional_keys__ == frozenset({"notice", "longRef"})
    assert "seq" in module.WelcomeFrame.__required_keys__ and "seq" in module.ErrorFrame.__optional_keys__
    assert "seq" not in module.HelloFrame.__annotations__


# --- the generated types under mypy --strict -------------------------------------------------------------------------

GOOD_USE = """
from protocol_types import Frame, HelloBody

def describe(frame: Frame) -> str:
    if frame["type"] == "hello":
        return frame["body"]["appVersion"]
    if frame["type"] == "welcome":
        return str(frame["seq"])
    return frame["type"]

HELLO: HelloBody = {"appVersion": "1", "protocol": 1, "lastAckedSeq": 0, "manifestHash": "h",
                    "glasses": {"model": "g2", "fw": "1"}}
"""
BAD_USE = """
from protocol_types import Frame, MsgInBody

def seq_of(frame: Frame) -> int:
    if frame["type"] == "hello":
        return frame["seq"]
    return 0

TEXT: MsgInBody = {"text": "x", "origin": "shout"}
"""


def _mypy(tmp_path: Path, use: str) -> tuple[str, int]:
    (tmp_path / "protocol_types.py").write_text(COMMITTED.read_text(encoding="utf-8"), encoding="utf-8")
    (tmp_path / "use.py").write_text(use, encoding="utf-8")
    cache = str(tmp_path / "cache")
    out, err, status = mypy_api.run([
        "--strict",
        "--cache-dir",
        cache,
        str(tmp_path / "protocol_types.py"),
        str(tmp_path / "use.py"),
    ])
    return out + err, status


def test_generated_module_passes_mypy_strict_and_narrows_on_type(tmp_path: Path) -> None:
    output, status = _mypy(tmp_path, GOOD_USE)
    assert status == 0, output


def test_mypy_rejects_seq_on_a_device_frame_and_a_bad_literal(tmp_path: Path) -> None:
    output, status = _mypy(tmp_path, BAD_USE)
    assert status == 1
    assert 'TypedDict "HelloFrame" has no key "seq"' in output
    assert "\"Literal['shout']\"" in output and "origin" in output


# --- unsupported schema features: error names the JSON pointer -------------------------------------------------------


def _set(name: str, key: str, value: object) -> Mutation:
    return lambda schema: _body(schema, name).__setitem__(key, value)


def _set_prop(name: str, prop: str, key: str, value: object) -> Mutation:
    return lambda schema: _body(schema, name)["properties"][prop].__setitem__(key, value)


@pytest.mark.parametrize(
    ("mutate", "expected"),
    [
        (_set("ping", "anyOf", []), "#/$defs/body.ping/anyOf: unsupported keyword 'anyOf'"),
        (_set_prop("msg.in", "text", "type", "number"), "#/$defs/body.msg.in/properties/text/type: unsupported"),
        (
            _set_prop("hello", "glasses", "patternProperties", {}),
            "#/$defs/body.hello/properties/glasses/patternProperties",
        ),
        (_set_prop("welcome", "lanes", "prefixItems", []), "#/$defs/body.welcome/properties/lanes/prefixItems"),
        (_set_prop("ack", "upToSeq", "$ref", "other.json#/x"), "#/$defs/body.ack/properties/upToSeq/$ref: only refs"),
        (_set_prop("ack", "upToSeq", "$ref", "#/$defs/body.ping"), "referenced only by the envelope dispatch"),
        (_set_prop("ack", "upToSeq", "enum", [1.5]), "#/$defs/body.ack/properties/upToSeq/enum: only string"),
        (_set("ack", "additionalProperties", True), "#/$defs/body.ack/additionalProperties: an object with"),
        (
            lambda s: _body(s, "msg.out")["allOf"][0]["then"].__setitem__("anyOf", []),
            "#/$defs/body.msg.out/allOf/0/then/anyOf: unsupported keyword",
        ),
        (
            lambda s: _body(s, "meeting.control")["then"].__setitem__("required", ["hintLvl"]),
            "#/$defs/body.meeting.control/then/required: 'hintLvl' is not a declared property",
        ),
        (_set("ack", "required", ["upToSeq", "nope"]), "#/$defs/body.ack/required: 'nope' is not a declared"),
        (
            lambda s: _body(s, "ack")["properties"].__setitem__("class", {"type": "string"}),
            "#/$defs/body.ack/properties/class: property name 'class' is not an identifier",
        ),
        (lambda s: _body(s, "ping").__setitem__("type", "string"), "#/$defs/body.ping: a body must be an object"),
        (lambda s: s.__setitem__("anyOf", []), "#/anyOf: unsupported keyword"),
    ],
)
def test_unsupported_schema_feature_names_its_path(mutate: Mutation, expected: str) -> None:
    assert expected in _error(mutate)


# --- the envelope dispatch and the README directions -----------------------------------------------------------------


def _drop_body_block(name: str) -> Mutation:
    def mutate(schema: Any) -> None:
        schema["allOf"] = [b for b in _blocks(schema) if f'"const": "{name}"' not in json.dumps(b)]

    return mutate


@pytest.mark.parametrize(
    ("mutate", "expected"),
    [
        (lambda s: _blocks(s).append(copy.deepcopy(_blocks(s)[2])), "type 'hello' has a second body definition"),
        (_drop_body_block("hello"), "type 'hello' needs exactly one body block"),
        (lambda s: _defs(s).__setitem__("body.extra", {"type": "object"}), "without a dispatch block: ['body.extra']"),
        (lambda s: _blocks(s)[2].__setitem__("else", {}), "#/allOf/2/else: unsupported keyword"),
        (
            lambda s: _blocks(s)[2]["if"]["properties"]["type"].__setitem__("const", "nope"),
            "#/allOf/2/if/properties/type: 'nope' is not in the `type` enum",
        ),
        (
            lambda s: _blocks(s)[2]["then"]["properties"]["body"].__setitem__("$ref", "#/$defs/body.welcome"),
            "#/allOf/2/then: expected a seq rule or properties.body.$ref '#/$defs/body.hello'",
        ),
        (
            lambda s: _blocks(s)[0]["if"]["properties"]["type"]["enum"].append("hello"),
            "type 'hello' both requires and forbids seq",
        ),
    ],
)
def test_dispatch_errors(mutate: Mutation, expected: str) -> None:
    assert expected in _error(mutate)


def test_readme_row_missing_or_direction_contradicting_seq_fails() -> None:
    no_row = README.replace("| `ack` | D→S |", "| ack | D→S |")
    assert "missing ['ack']" in _error(lambda s: None, no_row)
    wrong = README.replace("| `hello` | D→S |", "| `hello` | S→D |")
    assert "type 'hello' is S→D in protocol/README.md but seq is absent" in _error(lambda s: None, wrong)
    twice = README.replace("| `ack` | D→S |", "| `ack` | D→S |\n| `ack` | D→S |")
    assert "type 'ack' has two rows" in _error(lambda s: None, twice)


# --- the CLI ---------------------------------------------------------------------------------------------------------


def _tree(tmp_path: Path, schema: Any) -> Path:
    (tmp_path / "protocol").mkdir()
    (tmp_path / gen_protocol.SCHEMA).write_text(json.dumps(schema), encoding="utf-8")
    (tmp_path / gen_protocol.README).write_text(README, encoding="utf-8")
    return tmp_path


def test_cli_writes_module_and_a_schema_edit_changes_it(tmp_path: Path) -> None:
    schema = copy.deepcopy(SCHEMA)
    _body(schema, "ack")["properties"]["note"] = {"type": "string"}
    root = _tree(tmp_path, schema)
    assert gen_protocol.main(["--root", str(root)]) == 0
    written = (root / gen_protocol.OUTPUT).read_text(encoding="utf-8")
    assert "    note: NotRequired[str]\n" in written
    assert written != COMMITTED.read_text(encoding="utf-8")
    names = sorted(path.name for path in (root / gen_protocol.OUTPUT_DIR).iterdir())
    assert names == ["__init__.py", "protocol_types.py"]


def test_cli_reports_schema_error_with_path(tmp_path: Path, capsys: pytest.CaptureFixture[str]) -> None:
    schema = copy.deepcopy(SCHEMA)
    _body(schema, "ping")["anyOf"] = []
    out = tmp_path / "out"
    assert gen_protocol.main(["--root", str(_tree(tmp_path, schema)), "--out-dir", str(out)]) == 2
    assert "gen_protocol: protocol/envelope.schema.json#/$defs/body.ping/anyOf: unsupported" in capsys.readouterr().err
    assert not out.exists()


@pytest.mark.parametrize(
    ("damage", "expected"),
    [
        (lambda root: (root / gen_protocol.SCHEMA).unlink(), "envelope.schema.json: cannot read: No such file"),
        (lambda root: (root / gen_protocol.README).unlink(), "README.md: cannot read: No such file"),
        (lambda root: (root / gen_protocol.SCHEMA).write_text("{", encoding="utf-8"), "invalid JSON: Expecting"),
        (lambda root: (root / gen_protocol.README).write_bytes(b"\xff"), "README.md: not UTF-8: invalid start byte"),
    ],
)
def test_cli_unreadable_input_is_one_clean_line(
    tmp_path: Path, capsys: pytest.CaptureFixture[str], damage: Callable[[Path], None], expected: str
) -> None:
    root = _tree(tmp_path, SCHEMA)
    damage(root)
    assert gen_protocol.main(["--root", str(root), "--out-dir", str(tmp_path / "out")]) == 2
    err = capsys.readouterr().err
    assert err.startswith("gen_protocol: ") and err.count("\n") == 1 and expected in err, err
    assert "Traceback" not in err
    assert not (tmp_path / "out").exists()


def test_cli_unwritable_output_is_one_clean_line(tmp_path: Path, capsys: pytest.CaptureFixture[str]) -> None:
    blocker = tmp_path / "file"
    blocker.write_text("", encoding="utf-8")
    assert gen_protocol.main(["--out-dir", str(blocker / "out")]) == 2
    err = capsys.readouterr().err
    assert err.startswith("gen_protocol: ") and err.count("\n") == 1 and "cannot write" in err, err
