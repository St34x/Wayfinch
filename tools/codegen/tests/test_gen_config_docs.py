@pytest.mark.parametrize(
    ("content", "expected"),
    [(None, "cannot read"), ("{", "invalid JSON"), ("[]", "expected a JSON object"), (b"\xff", "not UTF-8")],
    ids=["missing", "invalid-json", "not-object", "not-utf8"],
)
def test_unreadable_schema_exits_2_with_one_line(tmp_path: Path, content: str | bytes | None, expected: str) -> None:
    schema = tmp_path / gen.SCHEMA
    schema.parent.mkdir(parents=True)
    if isinstance(content, str):
        schema.write_text(content, encoding="utf-8")
    elif content is not None:
        schema.write_bytes(content)
    for args in ([], ["--check"]):
        done = _run("--root", str(tmp_path), "--out-dir", str(tmp_path / "out"), *args)
        assert done.returncode == 2
        assert done.stderr.startswith(f"gen_config_docs: {gen.SCHEMA.as_posix()}")
        assert expected in done.stderr and done.stderr.count("\n") == 1
    assert not (tmp_path / "out").exists()


@pytest.mark.parametrize(
    ("mutate", "expected"),
    [
        (lambda s: s.update(allOf=[]), "#: keyword 'allOf'"),
        (lambda s: s["properties"]["port"].update(oneOf=[]), "#/properties/port: keyword 'oneOf'"),
        (lambda s: s["$defs"]["lane"].update(format="x"), "#/$defs/lane: keyword 'format'"),
        (lambda s: s["properties"]["lanes"]["items"].update({"$ref": "#/$defs/nope"}), "only an existing local"),
        (lambda s: s["properties"]["host"].update({"$ref": "other.json#/x"}), "#/properties/host/$ref"),
        (lambda s: s["properties"]["host"].update({"not": {"type": "null"}}), "#/properties/host/not"),
        (lambda s: s["properties"]["signer"].pop("additionalProperties"), "additionalProperties: false"),
        (lambda s: s["properties"].pop("public_url"), "EXAMPLES names a key the schema does not have: public_url"),
        (lambda s: s["properties"]["port"].update(description=1), "must be strings"),
        (lambda s: s.update(properties=[]), "#/properties: expected a JSON object"),
        (lambda s: s["properties"]["port"].update({"x-status": "done"}), "#/properties/port/x-status: only"),
        (lambda s: s["properties"]["lanes"].update(items=OBJECT_ITEMS), NESTED_ITEMS),
        (lambda s: s["properties"]["lanes"].update(items={"type": "array", "items": {"maxLength": 3}}), NESTED_ITEMS),
        (lambda s: s["properties"]["lanes"].update(items={"type": ["string", "object"]}), NESTED_ITEMS),
        (lambda s: s["properties"]["lanes"].update(items={"additionalProperties": True}), NESTED_ITEMS),
        (lambda s: s["$defs"]["lane"].update(properties={}), NESTED_ITEMS),
    ],
    ids=[
        *("root", "key", "def", "ref-missing", "ref-remote", "not", "open-object", "example", "prose", "props"),
        *("status", "object-items", "array-items", "type-list-items", "open-items", "ref-items"),
    ],
)
def test_unsupported_schema_raises_with_pointer(mutate: Mutation, expected: str) -> None:
    assert expected in _error(mutate)


def test_unsupported_schema_exits_2(tmp_path: Path) -> None:
    root = _root_with(tmp_path, lambda s: s["properties"]["port"].update(oneOf=[]))
    done = _run("--root", str(root), "--check")
    assert done.returncode == 2
    assert done.stderr == (
        f"gen_config_docs: {gen.SCHEMA.as_posix()}#/properties/port: keyword 'oneOf' is not supported by the docs "
        "generator\n"
    )


def test_nested_items_exit_2_with_one_line(tmp_path: Path) -> None:
    root = _root_with(tmp_path, lambda s: s["properties"]["lanes"].update(items=OBJECT_ITEMS))
    for args in ([], ["--check"]):
        done = _run("--root", str(root), "--out-dir", str(tmp_path / "out"), *args)
        assert (done.returncode, done.stderr) == (2, f"gen_config_docs: {gen.SCHEMA.as_posix()}{NESTED_ITEMS}\n")
    assert not (tmp_path / "out").exists()


# --- rendering --------------------------------------------------------------------------------------------------------


def test_range_text_forms() -> None:
    assert gen.range_text({"minimum": 0}) == "≥ 0"
    assert gen.range_text({"maximum": 9, "minLength": 2}) == "≤ 9; length ≥ 2"
    assert gen.range_text({"minItems": 1, "maxItems": 3, "uniqueItems": False}) == "items 1–3"
    assert gen.range_text({"const": "x", "not": {"const": "y"}}) == 'only `"x"`; not `"y"`'
    assert gen.range_text({"pattern": "^a|b$"}) == "pattern `^a\\|b$`"


def test_type_text_forms() -> None:
    assert gen.type_text(gen.Key("k", {"enum": ["a", 1]}, None)) == "integer or string"
    assert gen.type_text(gen.Key("k", {"type": ["object", "null"]}, None)) == "mapping or null"
    assert gen.type_text(gen.Key("k", {"type": "array"}, {"type": "integer"})) == "list of integer"


def test_prose_is_escaped_and_examples_win() -> None:
    schema = copy.deepcopy(SCHEMA)
    schema["properties"]["port"].update(description="a <b> | *c*", examples=[9000])
    row = next(line for line in gen.render(schema).splitlines() if line.startswith("| `port`"))
    assert row.endswith(f"| `9000` | {gen.PLANNED} a \\<b\\> \\| \\*c\\* |")
    assert "        port: 9000\n" in gen.render(schema)


def _row_of(schema: Any, path: str) -> str:
    return next(line for line in gen.render(schema).splitlines() if line.startswith(f"| `{path}` |"))


def test_planned_marker_is_rendered_and_inherited() -> None:
    schema = copy.deepcopy(SCHEMA)
    for node in (
        schema["properties"]["port"],
        schema["properties"]["signer"],
        schema["properties"]["signer"]["properties"]["socket"],
    ):
        node.pop("x-status", None)
    schema["properties"]["signer"]["x-status"] = "planned"
    assert gen.PLANNED not in _row_of(schema, "port")
    assert _row_of(schema, "port").endswith("| Loopback WebSocket port the TLS edge proxies /ws to. |")
    assert f"| {gen.PLANNED} Absolute path of the signer's unix socket" in _row_of(schema, "signer.socket")
    schema["properties"]["meeting"]["properties"]["enabled"].pop("x-status")
    assert _row_of(schema, "meeting.enabled").endswith(f"| {gen.PLANNED} |")


def test_status_note_says_pre_alpha() -> None:
    text = COMMITTED.read_text(encoding="utf-8")
    assert text.split("\n\n")[1].startswith("**Status: pre-alpha.**")


def test_unconstrained_items_render_no_each_cell() -> None:
    schema = copy.deepcopy(SCHEMA)
    schema["properties"]["lanes"]["items"] = {"type": "string"}
    row = _row_of(schema, "lanes")
    assert "| list of string | " in row and "each" not in row and "any" not in row.split("|")[4]


def test_code_span_with_backtick_uses_double_backticks() -> None:
    assert gen.range_text({"pattern": "^a`b$"}) == "pattern `` ^a`b$ ``"


def test_doc_and_generator_name_no_private_documents() -> None:
    private = re.compile("ADR" + r"-\d|\." + "team/")
    for path in (COMMITTED, SCRIPT, ROOT / gen.SCHEMA):
        assert not private.search(path.read_text(encoding="utf-8")), path
