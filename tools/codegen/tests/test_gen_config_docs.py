"""Tests of tools/codegen/gen_config_docs.py (T1.106): config schema -> docs/reference/config.md + freshness check."""

import copy
import json
import re
import shutil
import subprocess
import sys
from collections.abc import Callable
from pathlib import Path
from typing import Any

import gen_config_docs as gen
import pytest
import yaml
from protocol_model import CodegenError

# tools/codegen is on sys.path through conftest.py.
ROOT = Path(__file__).resolve().parents[3]
SCRIPT = ROOT / "tools/codegen/gen_config_docs.py"
DOCS = ROOT / gen.OUTPUT_DIR
COMMITTED = ROOT / gen.OUTPUT
# Any: the tests edit arbitrary nested schema nodes.
SCHEMA: Any = json.loads((ROOT / gen.SCHEMA).read_text(encoding="utf-8"))
Mutation = Callable[[Any], object]
OBJECT_ITEMS = {
    "type": "object",
    "additionalProperties": True,
    "properties": {"lane": {"type": "string", "maxLength": 3}},
}
NESTED_ITEMS = "#/properties/lanes/items: list items that are mappings or lists are not supported by the docs generator"

if str(ROOT / "hermes-plugin") not in sys.path:
    sys.path.insert(0, str(ROOT / "hermes-plugin"))


def _run(*args: str) -> subprocess.CompletedProcess[str]:
    return subprocess.run([sys.executable, str(SCRIPT), *args], capture_output=True, text=True, check=False, cwd=ROOT)


def _root_with(tmp_path: Path, mutate: Mutation) -> Path:
    schema = copy.deepcopy(SCHEMA)
    mutate(schema)
    path = tmp_path / "root" / gen.SCHEMA
    path.parent.mkdir(parents=True)
    path.write_text(json.dumps(schema), encoding="utf-8")
    return tmp_path / "root"


def _docs_copy(tmp_path: Path) -> Path:
    copy_dir = tmp_path / "reference"
    shutil.copytree(DOCS, copy_dir)
    return copy_dir


def _error(mutate: Mutation) -> str:
    schema = copy.deepcopy(SCHEMA)
    mutate(schema)
    with pytest.raises(CodegenError) as caught:
        gen.render(schema)
    return str(caught.value)


def _example() -> Any:
    block = re.search(r"```yaml\n(.*?)```", COMMITTED.read_text(encoding="utf-8"), re.DOTALL)
    assert block is not None
    return yaml.safe_load(block[1])["gateway"]["platforms"]["glasses"]["extra"]


def _paths(properties: Any, prefix: str = "") -> list[str]:
    found = []
    for name, node in properties.items():
        found.append(prefix + name)
        found += _paths(node.get("properties", {}), f"{prefix}{name}.")
    return found


# --- the committed document -------------------------------------------------------------------------------------------


def test_committed_doc_is_fresh() -> None:
    assert gen.generate(ROOT) == COMMITTED.read_text(encoding="utf-8")
    done = _run("--check")
    assert done.returncode == 0, done.stdout + done.stderr
    assert f"check-codegen: {COMMITTED} matches the generator" in done.stdout


def test_header_marks_the_doc_generated() -> None:
    lines = COMMITTED.read_text(encoding="utf-8").splitlines()
    assert re.fullmatch(r"<!-- @generated by tools/codegen/gen_config_docs\.py from \S+ - do not edit\. -->", lines[0])
    assert "SPDX-License-Identifier: Apache-2.0" in "\n".join(lines[:10])


def test_every_key_has_one_row_with_six_cells() -> None:
    rows = [line for line in COMMITTED.read_text(encoding="utf-8").splitlines() if line.startswith("| `")]
    keys = [row.split("`", 2)[1] for row in rows]
    assert keys == _paths(SCHEMA["properties"])
    assert all(len(re.split(r"(?<!\\)\|", row)) == 8 for row in rows)
    port = next(row for row in rows if row.startswith("| `port`"))
    assert port == (
        "| `port` | integer | `8765` | 1–65535 | `8765` | **Planned** — accepted and validated, no effect yet. "
        "Loopback WebSocket port the TLS edge proxies /ws to. |"
    )


def test_example_passes_the_plugin_validator() -> None:
    """glasses.config.check: the schema (jsonschema) plus the rules a schema cannot express."""
    from glasses import config as gcfg

    example = _example()
    assert list(example) == list(SCHEMA["properties"])
    result = gcfg.check(example)
    assert (result.errors, result.warnings) == ([], [])


# --- freshness --------------------------------------------------------------------------------------------------------


@pytest.mark.parametrize(
    "mutate",
    [
        lambda s: s["properties"]["port"].update(description="Changed."),
        lambda s: s["properties"]["port"].update(maximum=65534),
        lambda s: s["properties"]["meeting"]["properties"].pop("live_notes"),
        lambda s: s["properties"].update(extra_key={"type": "boolean", "default": True}),
    ],
    ids=["description", "range", "removed-key", "new-key"],
)
def test_schema_change_without_regeneration_fails(tmp_path: Path, mutate: Mutation) -> None:
    done = _run("--root", str(_root_with(tmp_path, mutate)), "--out-dir", str(DOCS), "--check")
    assert done.returncode == 1, done.stdout + done.stderr
    assert "+++" in done.stdout
    assert "is stale" in done.stderr


def _symlink_to_copy(docs: Path) -> None:
    target = docs.parent / "elsewhere.md"
    (docs / "config.md").rename(target)
    (docs / "config.md").symlink_to(target)


def _directory_in_place(docs: Path) -> None:
    (docs / "config.md").unlink()
    (docs / "config.md").mkdir()


@pytest.mark.parametrize(
    ("damage", "problem"),
    [
        (
            lambda d: (d / "config.md").write_text("edited\n", encoding="utf-8"),
            "is stale (edited, or the schema changed)",
        ),
        (lambda d: (d / "config.md").unlink(), "is missing"),
        (_symlink_to_copy, "is a symlink, not the generated file"),
        (_directory_in_place, "is not a regular file"),
    ],
    ids=["edited", "missing-doc", "symlink", "directory"],
)
def test_edited_missing_or_replaced_doc_fails(tmp_path: Path, damage: Mutation, problem: str) -> None:
    copy_dir = _docs_copy(tmp_path)
    damage(copy_dir)
    done = _run("--out-dir", str(copy_dir), "--check")
    assert done.returncode == 1, done.stdout + done.stderr
    assert done.stderr == f"check-codegen: {copy_dir / 'config.md'} {problem}; run: {gen.REGENERATE}\n"


def test_edited_doc_shows_a_unified_diff(tmp_path: Path) -> None:
    copy_dir = _docs_copy(tmp_path)
    (copy_dir / "config.md").write_text("edited\n", encoding="utf-8")
    done = _run("--out-dir", str(copy_dir), "--check")
    assert "-edited\n" in done.stdout and f"+++ {copy_dir / 'config.md'} (generated)" in done.stdout


def test_other_files_in_the_directory_are_not_owned(tmp_path: Path) -> None:
    """Other generators write next to config.md: their files neither fail the check nor get removed."""
    copy_dir = _docs_copy(tmp_path)
    (copy_dir / "cli.md").write_text("x\n", encoding="utf-8")
    (copy_dir / "sub").mkdir()
    assert _run("--out-dir", str(copy_dir), "--check").returncode == 0
    assert _run("--out-dir", str(copy_dir)).returncode == 0
    assert (copy_dir / "cli.md").read_text(encoding="utf-8") == "x\n" and (copy_dir / "sub").is_dir()


def test_missing_doc_directory_fails(tmp_path: Path) -> None:
    done = _run("--out-dir", str(tmp_path / "absent"), "--check")
    assert done.returncode == 1
    assert "is missing" in done.stderr


def test_write_mode_regenerates_the_doc(tmp_path: Path) -> None:
    assert _run("--out-dir", str(tmp_path / "out")).returncode == 0
    assert (tmp_path / "out/config.md").read_text(encoding="utf-8") == COMMITTED.read_text(encoding="utf-8")


def test_write_mode_replaces_a_symlink_without_writing_through_it(tmp_path: Path) -> None:
    target = tmp_path / "elsewhere.md"
    target.write_text("keep\n", encoding="utf-8")
    (tmp_path / "out").mkdir()
    (tmp_path / "out/config.md").symlink_to(target)
    assert _run("--out-dir", str(tmp_path / "out")).returncode == 0
    assert not (tmp_path / "out/config.md").is_symlink()
    assert target.read_text(encoding="utf-8") == "keep\n"
    assert _run("--out-dir", str(tmp_path / "out"), "--check").returncode == 0


