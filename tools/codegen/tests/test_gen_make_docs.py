"""gen_make_docs.py end to end: a fake repository tree (Makefile, mk/*.mk, ENGINEERING.md section 10, public docs,
git index) is clean after generation, and each planted rule violation exits 1 with a `file:line:` finding. One test
runs the gate over the real tree."""

import shutil
import subprocess
import sys
from pathlib import Path

import gen_make_docs as gen
import pytest

ROOT = Path(__file__).resolve().parents[3]
SCRIPT = ROOT / "tools/codegen/gen_make_docs.py"

MAKEFILE = """\
TEST_TARGETS :=
-include $(sort $(wildcard mk/*.mk))
.PHONY: help test

#: help — list the targets
help:
\t@echo help

#: test — run every test target
test: $(TEST_TARGETS)
\t@echo ok
"""
FRAGMENT = """\
# SPDX-License-Identifier: Apache-2.0
.PHONY: test-alpha alpha-up
TEST_TARGETS += test-alpha

#: test-alpha — alpha unit tests
test-alpha:
\t@true

#: alpha-up — start alpha by hand
alpha-up:
\t@true
"""
GATES = """\
# Engineering

## 10. Gates

| Rule | Make target | State |
|---|---|---|
| Alpha works | `test-alpha` | live |
| Commit subjects | `check_hygiene.py --commits` | live at merge time; CI planned |
| Beta later | `check-beta` | planned |

## 11. Other
"""
README = """\
# Demo

Run `make test`, `make -f mk/alpha.mk PY=x test-alpha` or `make <target>`; prose can make this work.

```sh
make help        # list
VENV=/tmp/v make alpha-up && make check-beta
```
"""


def _run(root: Path, *args: str) -> subprocess.CompletedProcess[str]:
    argv = [sys.executable, str(SCRIPT), "--root", str(root), *args]
    return subprocess.run(argv, capture_output=True, text=True, check=False)


def _git_add(root: Path) -> None:
    subprocess.run(["git", "init", "-q", str(root)], check=True)
    subprocess.run(["git", "-C", str(root), "add", "-A"], check=True)


@pytest.fixture
def tree(tmp_path: Path) -> Path:
    root = tmp_path / "repo"
    (root / "mk").mkdir(parents=True)
    (root / "Makefile").write_text(MAKEFILE, encoding="utf-8")
    (root / "mk/alpha.mk").write_text(FRAGMENT, encoding="utf-8")
    (root / "ENGINEERING.md").write_text(GATES, encoding="utf-8")
    (root / "README.md").write_text(README, encoding="utf-8")
    (root / gen.PRIVATE).mkdir()
    (root / gen.PRIVATE / "notes.md").write_text("`make private-only`\n", encoding="utf-8")
    assert _run(root).returncode == 0
    _git_add(root)
    return root


def _edit(path: Path, old: str, new: str) -> None:
    text = path.read_text(encoding="utf-8")
    assert text.count(old) == 1
    path.write_text(text.replace(old, new), encoding="utf-8")


def _fails(root: Path, where: str) -> str:
    done = _run(root, "--check")
    assert done.returncode == 1, done.stderr
    assert where in done.stderr, done.stderr
    return done.stderr


def test_generated_tree_is_clean(tree: Path) -> None:
    done = _run(tree, "--check")
    assert done.returncode == 0, done.stderr
    assert "4 targets" in done.stdout


def test_reference_lists_targets_with_description_run_flag_and_file(tree: Path) -> None:
    text = (tree / gen.OUTPUT).read_text(encoding="utf-8")
    assert text.startswith("<!-- @generated by tools/codegen/gen_make_docs.py")
    assert "| `alpha-up` | start alpha by hand | no | `mk/alpha.mk` |" in text
    assert "| `test-alpha` | alpha unit tests | yes | `mk/alpha.mk` |" in text
    assert "| `test` | run every test target | — | `Makefile` |" in text
    assert text.index("`alpha-up`") < text.index("`help`") < text.index("`test`")


def test_generation_is_deterministic(tree: Path) -> None:
    before = (tree / gen.OUTPUT).read_bytes()
    assert _run(tree).returncode == 0
    assert (tree / gen.OUTPUT).read_bytes() == before


def test_target_without_description_line_fails(tree: Path) -> None:
    _edit(tree / "mk/alpha.mk", "#: alpha-up — start alpha by hand\n", "")
    assert "mk/alpha.mk:9: target `alpha-up` has no `#:` line" in _fails(tree, "mk/alpha.mk:9:")


def test_generation_refuses_while_a_description_is_missing(tree: Path) -> None:
    _edit(tree / "mk/alpha.mk", "#: alpha-up — start alpha by hand\n", "")
    before = (tree / gen.OUTPUT).read_bytes()
    assert _run(tree).returncode == 1
    assert (tree / gen.OUTPUT).read_bytes() == before


def test_stale_reference_fails_with_a_diff(tree: Path) -> None:
    _edit(tree / "mk/alpha.mk", "alpha unit tests", "alpha unit tests, renamed")
    done = _run(tree, "--check")
    assert done.returncode == 1
    assert "docs/reference/make-targets.md:1: is stale" in done.stderr
    assert "+| `test-alpha` | alpha unit tests, renamed" in done.stdout


@pytest.mark.parametrize("kind", ["missing", "symlink", "directory"])
def test_reference_not_a_regular_file_fails(tree: Path, kind: str) -> None:
    out = tree / gen.OUTPUT
    moved = tree / "elsewhere.md"
    shutil.move(out, moved)
    if kind == "symlink":
        out.symlink_to(moved)
    elif kind == "directory":
        out.mkdir()
    _fails(tree, "docs/reference/make-targets.md:1: is missing, a symlink or not a regular file")


def test_other_files_next_to_the_reference_are_not_owned(tree: Path) -> None:
    (tree / gen.OUTPUT_DIR / "config.md").write_text("hand edited\n", encoding="utf-8")
    assert _run(tree, "--check").returncode == 0


def test_test_target_without_gate_row_fails(tree: Path) -> None:
    _edit(tree / "ENGINEERING.md", "| Alpha works | `test-alpha` | live |\n", "")
    _fails(tree, "mk/alpha.mk:3: `make test` runs `test-alpha`, but no live row")


def test_test_target_in_a_planned_row_only_fails(tree: Path) -> None:
    _edit(tree / "ENGINEERING.md", "`test-alpha` | live", "`test-alpha` | planned")
    _fails(tree, "mk/alpha.mk:3: `make test` runs `test-alpha`, but no live row")


def test_live_row_naming_an_undefined_target_fails(tree: Path) -> None:
    _edit(tree / "ENGINEERING.md", "`check-beta` | planned", "`check-beta` | live")
    _fails(tree, "ENGINEERING.md:9: live row names `check-beta`, which no rule defines")


def test_live_row_without_a_code_span_fails(tree: Path) -> None:
    _edit(tree / "ENGINEERING.md", "| Alpha works | `test-alpha` | live |", "| Alpha works | test-alpha | live |")
    _fails(tree, "ENGINEERING.md:7: Make target cell names no target in a code span")


def test_public_doc_naming_an_unknown_target_fails(tree: Path) -> None:
    with (tree / "docs.md").open("w", encoding="utf-8") as handle:
        handle.write("# Docs\n\nThen run\n`make  test-gamma`.\n")
    _git_add(tree)
    _fails(tree, "docs.md:4: `make test-gamma`: no rule defines it")


def test_public_doc_fenced_block_naming_an_unknown_target_fails(tree: Path) -> None:
    _edit(tree / "README.md", "make help        # list", "make help\n$ cd x && make lint-gamma")
    _fails(tree, "README.md:7: `make lint-gamma`")


def test_untracked_and_private_docs_are_not_read(tree: Path) -> None:
    (tree / "untracked.md").write_text("`make nothing-here`\n", encoding="utf-8")
    assert _run(tree, "--check").returncode == 0


def test_root_that_is_not_a_git_top_cannot_be_checked(tree: Path) -> None:
    shutil.rmtree(tree / ".git")
    done = _run(tree, "--check")
    assert done.returncode == 2
    assert done.stderr.startswith("gen_make_docs: ")


@pytest.mark.parametrize("missing", ["Makefile", "mk", "ENGINEERING.md"])
def test_missing_input_cannot_be_checked(tree: Path, missing: str) -> None:
    path = tree / missing
    shutil.rmtree(path) if path.is_dir() else path.unlink()
    assert _run(tree, "--check").returncode == 2


def test_section_without_gate_table_cannot_be_checked(tree: Path) -> None:
    (tree / "ENGINEERING.md").write_text("# Engineering\n\n## 10. Gates\n\nNo table.\n", encoding="utf-8")
    assert _run(tree, "--check").returncode == 2


def test_make_files_without_targets_cannot_be_checked(tree: Path) -> None:
    (tree / "Makefile").write_text("X := 1\n", encoding="utf-8")
    (tree / "mk/alpha.mk").write_text("Y := 2\n", encoding="utf-8")
    assert _run(tree, "--check").returncode == 2


def test_real_tree_is_clean() -> None:
    done = subprocess.run([sys.executable, str(SCRIPT), "--check"], capture_output=True, text=True, check=False)
    assert done.returncode == 0, done.stderr
