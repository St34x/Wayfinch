"""Generate the plugin configuration reference from hermes-plugin/glasses/config.schema.json (ENGINEERING.md section 4).
Stdlib only.

Output: docs/reference/config.md - a status note, one table row per key (dotted path, type, default, range, example,
description) and a complete YAML example under gateway.platforms.glasses.extra. A key's example is its schema
`examples[0]`, else the EXAMPLES entry below (example.com values only), else its default. A key without a description
shows its x-hint. A key with `"x-status": "planned"` (or inside such a key) is marked as accepted and validated but
without effect yet. The generator owns exactly that one file, not the directory (other generators write their own
files next to it): `--check` regenerates it in memory and compares it byte for byte; a missing, edited or stale file,
or a symlink or anything else in its place fails. `make check-codegen` runs it.

Usage: gen_config_docs.py [--root DIR] [--out-dir DIR] [--check]   (defaults: this repository, its docs/reference)
Exit:  0 written / fresh; 1 stale (--check, unified diff on stdout); 2 an input cannot be read or the output cannot be
       written, or the schema uses a keyword or form the generator cannot represent (one line on stderr naming the
       file and the JSON pointer).
"""

import argparse
import difflib
import json
import re
import sys
from collections.abc import Iterator, Mapping
from dataclasses import dataclass
from pathlib import Path

from protocol_model import CodegenError

SCHEMA = Path("hermes-plugin/glasses/config.schema.json")
OUTPUT_DIR = Path("docs/reference")
OUTPUT = OUTPUT_DIR / "config.md"
REGENERATE = "python3 tools/codegen/gen_config_docs.py"
EXTRA_PATH = ("gateway", "platforms", "glasses", "extra")
# Example values where the default says nothing about a real deployment: example.com only, no deployment values.
EXAMPLES: Mapping[str, object] = {
    "public_url": "wss://glasses.example.com/ws",
    "meeting.endpoint": "stt.example.com",
}
LINE_BREAKS = "[\\n\\r\\u0085\\u2028\\u2029]"
ROOT_KEYWORDS = frozenset(
    {"$schema", "$id", "$comment", "title", "description", "type", "additionalProperties", "properties", "$defs"}
    | {"x-error", "x-hint"}
)
KEY_KEYWORDS = frozenset(
    {"description", "type", "default", "examples", "enum", "const", "not", "$ref", "items", "properties"}
    | {"minimum", "maximum", "minLength", "maxLength", "pattern", "minItems", "maxItems", "uniqueItems"}
    | {"additionalProperties", "x-error", "x-errors", "x-hint", "x-echo", "x-status"}
)
# Words that make a list item a mapping or a list; the table has no form for their inner keys, so they fail closed.
NESTED_ITEM_WORDS = frozenset({"items", "properties", "additionalProperties"})
MD_SPECIAL = re.compile(r"([\\`*_<>\[\]|&])")
HEADER = f"""<!-- @generated by tools/codegen/gen_config_docs.py from {SCHEMA} - do not edit. -->
<!-- Regenerate: {REGENERATE}   (make check-codegen fails while this file is stale) -->
<!-- SPDX-License-Identifier: Apache-2.0 -->
"""
# Project status shown under the title; change it when the plugin starts serving the glasses.
STATUS = (
    "**Status: pre-alpha.** The plugin validates these settings (when the gateway loads it, and with "
    "`python -m glasses.admin config check`) but does not serve the glasses yet. A key marked **Planned** is "
    "accepted and validated and has no effect yet.\n\n"
)
PLANNED = "**Planned** — accepted and validated, no effect yet."

Node = Mapping[str, object]


@dataclass(frozen=True)
class Key:
    """One documented key: dotted path, schema node ($ref resolved), array items node, JSON pointer, planned flag."""

    path: str
    node: Node
    items: Node | None
    pointer: str = "#"
    planned: bool = False


def _mapping(value: object, pointer: str) -> Node:
    if not isinstance(value, Mapping) or not all(isinstance(name, str) for name in value):
        raise CodegenError(f"{pointer}: expected a JSON object")
    return value


def _keywords(node: Node, allowed: frozenset[str], pointer: str) -> None:
    unknown = sorted(set(node) - allowed)
    if unknown:
        raise CodegenError(f"{pointer}: keyword {unknown[0]!r} is not supported by the docs generator")


def _resolve(node: Node, defs: Node, pointer: str) -> Node:
    """The node with a local `$ref` merged in (the referring node's own keywords win)."""
    _keywords(node, KEY_KEYWORDS, pointer)
    ref = node.get("$ref")
    if ref is None:
        return node
    if not isinstance(ref, str) or not ref.startswith("#/$defs/") or ref.removeprefix("#/$defs/") not in defs:
        raise CodegenError(f"{pointer}/$ref: only an existing local #/$defs/<name> reference is supported")
    target = _mapping(defs[ref.removeprefix("#/$defs/")], ref)
    return {**target, **{word: value for word, value in node.items() if word != "$ref"}}


def _items(node: Node, defs: Node, pointer: str) -> Node | None:
    """The resolved items node of a list key; items that are mappings or lists fail closed."""
    if "items" not in node:
        return None
    item = _resolve(_mapping(node["items"], f"{pointer}/items"), defs, f"{pointer}/items")
    declared = item.get("type")
    types = {str(name) for name in declared} if isinstance(declared, list) else {str(declared)}
    if types & {"object", "array"} or set(item) & NESTED_ITEM_WORDS:
        raise CodegenError(
            f"{pointer}/items: list items that are mappings or lists are not supported by the docs generator"
        )
    return item


def _planned(node: Node, pointer: str) -> bool:
    status = node.get("x-status")
    if status not in {None, "planned"}:
        raise CodegenError(f"{pointer}/x-status: only the value 'planned' is supported")
    return status == "planned"


def walk(properties: Node, defs: Node, parent: Key | None = None) -> Iterator[Key]:
    """Every key in document order, an object key before the keys inside it (which inherit its planned flag)."""
    prefix, pointer = (f"{parent.path}.", parent.pointer) if parent else ("", "#")
    for name in properties:
        at = f"{pointer}/properties/{name}"
        node = _resolve(_mapping(properties[name], at), defs, at)
        planned = _planned(node, at) or (parent is not None and parent.planned)
        key = Key(prefix + name, node, _items(node, defs, at), at, planned)
        yield key
        if "properties" in node:
            if node.get("additionalProperties") is not False:
                raise CodegenError(f"{at}: an object key must set additionalProperties: false")
            yield from walk(_mapping(node["properties"], f"{at}/properties"), defs, key)


def _json_type(value: object) -> str:
    names = {bool: "boolean", int: "integer", float: "number", str: "string", type(None): "null"}
    return names.get(type(value), "value")


def type_text(key: Key) -> str:
    """`string`, `string or null`, `list of string`; an enum without `type` takes the type of its values."""
    declared = key.node.get("type")
    if declared is None:
        values = key.node.get("enum", [key.node.get("const")])
        declared = sorted({_json_type(value) for value in values}) if isinstance(values, list) else "value"
    names = [str(name) for name in declared] if isinstance(declared, list) else [str(declared)]
    text = " or ".join("list" if name == "array" else "mapping" if name == "object" else name for name in names)
    if key.items is not None:
        text += " of " + type_text(Key("", key.items, None))
    return text


def _code(text: str) -> str:
    """A Markdown code span; a text with a backtick gets a double-backtick span."""
    text = text.replace("|", "\\|")
    return f"`` {text} ``" if "`" in text else f"`{text}`"


def _value(value: object) -> str:
    """A JSON value as a code span: strings quoted, so "" and null stay visible."""
    return _code(json.dumps(value, ensure_ascii=False))


def _bounds(node: Node, low: str, high: str, unit: str) -> list[str]:
    lo, hi = node.get(low), node.get(high)
    if lo is not None and hi is not None:
        return [f"{unit}{lo}–{hi}"]
    return [f"{unit}≥ {lo}"] if lo is not None else [f"{unit}≤ {hi}"] if hi is not None else []


def range_text(node: Node, pointer: str = "#") -> str:
    """Bounds, length, pattern, allowed values and exclusions of a node, `; `-separated."""
    parts = _bounds(node, "minimum", "maximum", "") + _bounds(node, "minLength", "maxLength", "length ")
    parts += _bounds(node, "minItems", "maxItems", "items ")
    parts += ["unique"] if node.get("uniqueItems") is True else []
    parts += [f"pattern {_code(str(node['pattern']))}"] if "pattern" in node else []
    enum = node.get("enum")
    parts += ["one of " + ", ".join(_value(value) for value in enum)] if isinstance(enum, list) else []
    parts += [f"only {_value(node['const'])}"] if "const" in node else []
    if "not" in node:
        parts.append(_exclusion(_mapping(node["not"], f"{pointer}/not"), f"{pointer}/not"))
    return "; ".join(parts)


def _exclusion(node: Node, pointer: str) -> str:
    if node == {"pattern": LINE_BREAKS}:
        return "no line breaks"
    if set(node) == {"const"}:
        return f"not {_value(node['const'])}"
    raise CodegenError(f"{pointer}: only not: {{const}} or the line-break pattern is supported")


def _prose(node: Node, pointer: str) -> str:
    text = node.get("description", node.get("x-hint", ""))
    if not isinstance(text, str):
        raise CodegenError(f"{pointer}: description and x-hint must be strings")
    return MD_SPECIAL.sub(r"\\\1", " ".join(text.split()))


def has_example(key: Key) -> bool:
    """A leaf key with schema examples, an EXAMPLES entry or a default (object keys show their keys instead)."""
    examples = key.node.get("examples")
    sources = (isinstance(examples, list) and bool(examples), key.path in EXAMPLES, "default" in key.node)
    return "properties" not in key.node and any(sources)


def example(key: Key) -> object:
    """examples[0], else EXAMPLES, else the default (call only when has_example)."""
    examples = key.node.get("examples")
    if isinstance(examples, list) and examples:
        return examples[0]
    return EXAMPLES[key.path] if key.path in EXAMPLES else key.node["default"]


def _row(key: Key) -> str:
    node = key.node
    default = _value(node["default"]) if "default" in node else "—"
    shown = _value(example(key)) if has_example(key) else "—"
    limits = range_text(node, key.pointer)
    each = "" if key.items is None else range_text(key.items, f"{key.pointer}/items")
    limits = "; ".join(filter(None, [limits, each and f"each: {each}"]))
    prose = " ".join(filter(None, [PLANNED if key.planned else "", _prose(node, key.pointer)]))
    cells = [_code(key.path), type_text(key), default, limits or "—", shown, prose or "—"]
    return "| " + " | ".join(cells) + " |\n"


def yaml_example(keys: list[Key]) -> Iterator[str]:
    """YAML lines of every key with an example, nested under EXTRA_PATH (walk order: an object before its keys)."""
    for depth, part in enumerate(EXTRA_PATH):
        yield f"{'  ' * depth}{part}:\n"
    for key in keys:
        pad = "  " * (len(EXTRA_PATH) + key.path.count("."))
        name = key.path.rsplit(".", 1)[-1]
        if "properties" in key.node:
            yield f"{pad}{name}:\n"
        elif has_example(key):
            yield f"{pad}{name}: {json.dumps(example(key), ensure_ascii=False)}\n"


def render(schema: Node) -> str:
    """The complete Markdown reference of a config schema (raises CodegenError)."""
    _keywords(schema, ROOT_KEYWORDS, "#")
    defs = _mapping(schema.get("$defs", {}), "#/$defs")
    for name in defs:
        _keywords(_mapping(defs[name], f"#/$defs/{name}"), KEY_KEYWORDS - {"$ref"}, f"#/$defs/{name}")
    keys = list(walk(_mapping(schema.get("properties"), "#/properties"), defs))
    unused = sorted(set(EXAMPLES) - {key.path for key in keys})
    if unused:
        raise CodegenError(f"#/properties: EXAMPLES names a key the schema does not have: {unused[0]}")
    title = schema.get("title", "glasses platform settings")
    parts = [HEADER, f"# Configuration reference: {title}\n\n", STATUS, _prose(schema, "#"), "\n\n"]
    parts += [f"Source: `{SCHEMA}`. Regenerate this file with `{REGENERATE}`.\n\n## Example\n\n"]
    parts += ["Every key with its default, URLs and host names as `example.com` placeholders:\n\n```yaml\n"]
    parts += [*yaml_example(keys), "```\n\n## Keys\n\n"]
    parts += ["| Key | Type | Default | Range | Example | Description |\n|---|---|---|---|---|---|\n"]
    parts += [_row(key) for key in keys]
    return "".join(parts)


def _read_schema(root: Path) -> Node:
    try:
        return _mapping(json.loads((root / SCHEMA).read_text(encoding="utf-8")), "#")
    except OSError as error:
        raise CodegenError(f"{SCHEMA}: cannot read: {error.strerror or error}") from None
    except UnicodeDecodeError as error:
        raise CodegenError(f"{SCHEMA}: not UTF-8: {error.reason} at byte {error.start}") from None
    except json.JSONDecodeError as error:
        raise CodegenError(f"{SCHEMA}: invalid JSON: {error.msg} (line {error.lineno} column {error.colno})") from None


def generate(root: Path) -> str:
    """The text of docs/reference/config.md for the schema under root (raises CodegenError)."""
    return render(_read_schema(root))


def _write(out: Path, text: str) -> None:
    """Write the generated file; a symlink in its place is replaced, never written through."""
    try:
        out.parent.mkdir(parents=True, exist_ok=True)
        if out.is_symlink():
            out.unlink()
        out.write_text(text, encoding="utf-8")
    except OSError as error:
        raise CodegenError(f"{error.filename or out}: cannot write: {error.strerror or error}") from None


def _not_fresh(out: Path, text: str) -> str:
    """Why out is not the generated file ("" = fresh); prints a unified diff when its content differs."""
    if out.is_symlink():
        return "is a symlink, not the generated file"
    if not out.exists():
        return "is missing"
    if not out.is_file():
        return "is not a regular file"
    try:
        current = out.read_bytes()
    except OSError as error:
        raise CodegenError(f"{out}: cannot read: {error.strerror or error}") from None
    if current == text.encode("utf-8"):
        return ""
    old = current.decode("utf-8", errors="replace").splitlines(keepends=True)
    sys.stdout.writelines(difflib.unified_diff(old, text.splitlines(keepends=True), str(out), f"{out} (generated)"))
    return "is stale (edited, or the schema changed)"


def check(out: Path, text: str) -> int:
    """Compare out with the generated text: 0 fresh, 1 not (one line on stderr naming the fix)."""
    problem = _not_fresh(out, text)
    if problem:
        sys.stderr.write(f"check-codegen: {out} {problem}; run: {REGENERATE}\n")
        return 1
    sys.stdout.write(f"check-codegen: {out} matches the generator\n")
    return 0


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description="Generate docs/reference/config.md from the plugin config schema.")
    parser.add_argument("--root", type=Path, default=Path(__file__).resolve().parents[2])
    parser.add_argument("--out-dir", type=Path, help=f"directory of {OUTPUT.name} (default: <root>/{OUTPUT_DIR})")
    parser.add_argument("--check", action="store_true", help="compare instead of writing (exit 1 when stale)")
    args = parser.parse_args(argv)
    out = (args.out_dir or args.root / OUTPUT_DIR) / OUTPUT.name
    try:
        text = generate(args.root)
        if args.check:
            return check(out, text)
        _write(out, text)
    except CodegenError as error:
        where = SCHEMA.as_posix() if str(error).startswith("#") else ""
        sys.stderr.write(f"gen_config_docs: {where}{error}\n")
        return 2
    return 0


if __name__ == "__main__":
    sys.exit(main())
