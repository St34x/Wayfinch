"""Generate the Python protocol types from protocol/envelope.schema.json (ENGINEERING.md section 4). Stdlib only.

Output: hermes-plugin/glasses/generated/protocol_types.py - `FrameType` Literal, one TypedDict per body (optional keys
`NotRequired`), one TypedDict per frame (`type` Literal + its body; `seq` required / absent / optional per the schema's
seq rule) and the `Frame` union mypy narrows on `frame["type"]`, plus FRAME_TYPES and the direction sets
DEVICE_TO_SERVER / SERVER_TO_DEVICE (from the protocol/README.md "Message types" table). The generator owns the whole
directory: it writes every file in it (`__init__.py` too), and `make check-codegen` (tools/codegen/check_fresh.sh)
regenerates the directory into a temporary one and fails on any extra, missing or different file (`diff -r`).

Usage: gen_protocol.py [--root DIR] [--out-dir DIR]   (defaults: this repository, its generated directory)
Exit:  0 written; 2 an input cannot be read, or the schema uses something the generator cannot represent (one line
       on stderr naming the file and, for the schema, the JSON pointer).
"""

import argparse
import json
import sys
from pathlib import Path

from protocol_envelope import build_model
from protocol_model import (
    CodegenError,
    Field,
    Frame,
    ListOf,
    Literals,
    Named,
    OpenObject,
    ProtocolModel,
    Scalar,
    TypeExpr,
)

SCHEMA = Path("protocol/envelope.schema.json")
README = Path("protocol/README.md")
OUTPUT_DIR = Path("hermes-plugin/glasses/generated")
OUTPUT = OUTPUT_DIR / "protocol_types.py"
INIT = (
    "# SPDX-License-Identifier: Apache-2.0\n"
    '"""Code generated from the protocol schema by tools/codegen (never edited by hand; see protocol_types.py)."""\n'
)
HEADER = f'''# SPDX-License-Identifier: Apache-2.0
# @generated by tools/codegen/gen_protocol.py from {SCHEMA} and {README} - do not edit.
# Regenerate: python3 tools/codegen/gen_protocol.py   (make check-codegen fails while this file is stale)
"""Wayfinch envelope v1 types (structural).

Bounds, patterns and the conditional rules (if/then, oneOf, dependentRequired) are not expressed here: the schema and
the codec enforce them. Narrow a `Frame` on `frame["type"]` to get its body type.
"""

from typing import Final, Literal, NotRequired, TypeAlias, TypedDict
'''


def _literal(value: str | int | bool) -> str:
    return json.dumps(value) if isinstance(value, str) else repr(value)


def py_type(expr: TypeExpr) -> str:
    """Python annotation of a model type expression."""
    if isinstance(expr, Scalar):
        return expr.name
    if isinstance(expr, Literals):
        return f"Literal[{', '.join(_literal(value) for value in expr.values)}]"
    if isinstance(expr, Named):
        return expr.name
    if isinstance(expr, ListOf):
        return f"list[{py_type(expr.item)}]"
    if isinstance(expr, OpenObject):
        return "dict[str, object]"
    raise TypeError(expr)


def _field(field: Field) -> str:
    annotation = py_type(field.type)
    return f"    {field.name}: {annotation if field.required else f'NotRequired[{annotation}]'}\n"


def _class(name: str, base: str, lines: list[str]) -> str:
    return f"\n\nclass {name}({base}):\n" + ("".join(lines) or "    pass\n")


def _frame_name(frame: Frame) -> str:
    return frame.body.removesuffix("Body") + "Frame"


def _frame(frame: Frame, seq_type: str) -> str:
    seq = {"required": [f"    seq: {seq_type}\n"], "optional": [f"    seq: NotRequired[{seq_type}]\n"], "absent": []}
    lines = [f"    type: Literal[{_literal(frame.type_name)}]\n", *seq[frame.seq], f"    body: {frame.body}\n"]
    return _class(_frame_name(frame), "FrameHeader", lines)


def _union(name: str, members: list[str]) -> str:
    return f"\n\n{name}: TypeAlias = (\n    " + "\n    | ".join(members) + "\n)\n"


def _type_set(name: str, types: list[str]) -> str:
    items = "".join(f"    {_literal(value)},\n" for value in types)
    return f"{name}: Final[frozenset[FrameType]] = frozenset({{\n{items}}})\n"


def emit_python(model: ProtocolModel) -> str:
    """The complete generated module text."""
    types = "".join(f"    {_literal(name)},\n" for name in model.frame_types)
    parts = [HEADER, f"\nFrameType: TypeAlias = Literal[\n{types}]\n\n"]
    parts.append(f"FRAME_TYPES: Final[tuple[FrameType, ...]] = (\n{types})\n\n")
    parts += [f"{alias.name}: TypeAlias = {py_type(alias.type)}\n" for alias in model.aliases]
    parts += [_class(struct.name, "TypedDict", [_field(f) for f in struct.fields]) for struct in model.structs]
    parts.append(_class("FrameHeader", "TypedDict", [_field(f) for f in model.header]))
    parts += [_frame(frame, py_type(model.seq_type)) for frame in model.frames]
    parts.append(_union("Body", [frame.body for frame in model.frames]))
    parts.append(_union("Frame", [_frame_name(frame) for frame in model.frames]) + "\n")
    parts.append(_type_set("DEVICE_TO_SERVER", [f.type_name for f in model.frames if f.direction != "S→D"]))
    parts.append(_type_set("SERVER_TO_DEVICE", [f.type_name for f in model.frames if f.direction != "D→S"]))
    return "".join(parts)


def _read(path: Path) -> str:
    try:
        return path.read_text(encoding="utf-8")
    except OSError as error:
        raise CodegenError(f"{path}: cannot read: {error.strerror or error}") from None
    except UnicodeDecodeError as error:
        raise CodegenError(f"{path}: not UTF-8: {error.reason} at byte {error.start}") from None


def generate(root: Path) -> str:
    """Read the schema and README under `root` and return the module text (raises CodegenError)."""
    try:
        schema = json.loads(_read(root / SCHEMA))
    except json.JSONDecodeError as error:
        raise CodegenError(f"{SCHEMA}: invalid JSON: {error.msg} (line {error.lineno} column {error.colno})") from None
    if not isinstance(schema, dict):
        raise CodegenError(f"{SCHEMA}: the schema is not a JSON object")
    return emit_python(build_model(schema, _read(root / README)))


def generate_dir(root: Path) -> dict[str, str]:
    """Every file of the generated directory: name -> text (raises CodegenError)."""
    return {"__init__.py": INIT, OUTPUT.name: generate(root)}


def _write(out_dir: Path, files: dict[str, str]) -> None:
    try:
        out_dir.mkdir(parents=True, exist_ok=True)
        for name, text in files.items():
            (out_dir / name).write_text(text, encoding="utf-8")
    except OSError as error:
        raise CodegenError(f"{error.filename or out_dir}: cannot write: {error.strerror or error}") from None


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description="Generate the Python protocol types from the envelope schema.")
    parser.add_argument("--root", type=Path, default=Path(__file__).resolve().parents[2])
    parser.add_argument("--out-dir", type=Path, help=f"output directory (default: <root>/{OUTPUT_DIR})")
    args = parser.parse_args(argv)
    try:
        _write(args.out_dir or args.root / OUTPUT_DIR, generate_dir(args.root))
    except CodegenError as error:
        where = SCHEMA.as_posix() if str(error).startswith("#") else ""
        sys.stderr.write(f"gen_protocol: {where}{error}\n")
        return 2
    return 0


if __name__ == "__main__":
    sys.exit(main())
