"""The fixed Kotlin text of Envelope.kt: header, support types, the strict decoder and the envelope serializer.

Only `{package}`, `{wire_params}`, `{decode_args}` and `{encode_args}` are filled in (by plain replacement) by
kotlin_emitter.py; everything else is copied as written. `RESERVED_TYPES` lists every type name this text uses, so a
schema `$defs` entry cannot shadow one (the emitter claims them first; a test keeps the list complete).

Strict decode, the design in one place. kotlinx-serialization is looser than the schema and the Python codec: it reads
unquoted literals (`abc`, `NaN`, `01`, `+1`, `'x'`, an unquoted enum value) and raw control characters in strings,
a quoted number (`"v": "1"`) or `1e0` as an integer, a quoted boolean as a boolean, an explicit `null` as an absent
optional field, a repeated object key as "the last one wins", and has no nesting limit. `decodeEnvelope(text)` is the
only decode entry and closes all of these, so text that is not JSON never becomes a typed `Envelope` (what it does not
check is listed in the header and in protocol/README.md):

1. the raw text is scanned first (`scanRawText`, one iterative pass, no JsonElement can show these): a bare value
   outside a string must be `true`, `false`, `null` or a number of RFC 8259 (a number with a fraction or exponent must
   convert to a finite double, so `1e999` is refused and `1e-999` accepted; an integer of more than 4300 digits is
   refused; Python's `json` does the same), which also makes an unquoted enum value or `NaN` fail;
   a character below U+0020 inside a string is refused; more than 35 open brackets at once are refused (the limit of
   the Python raw pre-scan, so the memory of the scan is bounded); and a repeated key is refused, comparing keys after
   unescaping (`"a"` and `"\\u0061"` are one key), in the open objects (`args`, `output`) too, like the Python hook;
2. the text is parsed to a JsonElement and `requireStrict` walks it together with the serial descriptor of the target
   class: any `null` is refused (the schema has no nullable type; an optional field is absent or has a value), an
   integer property must hold a number token matching `-?(0|[1-9][0-9]*)` inside its bounds (`@WireInteger`, written
   from the schema's `minimum`/`maximum`/`const`), a boolean must be an unquoted `true`/`false`. Open objects
   (`JsonObject` properties) are data and not walked, as in the Python codec;
3. the usual typed decode refuses the rest (unknown or missing keys, wrong shapes, unknown enum values, a
   malformed escape).

`EnvelopeSerializer` is internal and decodes only through the private `Json` of `decodeEnvelope`; any other decoder
(`envelopeJson.decodeFromString(Envelope.serializer(), ...)`) fails with a message naming `decodeEnvelope`, so no
lax path stays open. Encoding works with any `Json`: the serializer converts with `envelopeJson` itself.
"""

