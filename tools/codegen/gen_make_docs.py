"""Generate the make-target reference from the `#:` lines of the Makefile and mk/*.mk, and check the docs that name
make targets (ENGINEERING.md sections 9 and 10). Stdlib only; parsing rules: make_docs_model.py.

Output: docs/reference/make-targets.md - one table row per target (name, description, run by `make test` or not,
defining file). The generator owns exactly that one file, not the directory (other generators write their own files
next to it). `--check` (run by `make check-make-docs`) reports, one `file:line: …` finding per line on stderr:
- a defined target without a `#: <target> — <description>` line directly above its rule, or a misplaced `#:` line;
- the reference missing, edited, stale, or a symlink or anything else in its place (unified diff on stdout);
- a target `make test` runs (TEST_TARGETS, prerequisites of `test`) that no live row of ENGINEERING.md section 10
  names, and a live row naming a target no rule defines;
- a tracked public `*.md` (outside the private team folder `PRIVATE`) whose code span or fenced code block runs
  `make <t>` for a target that is neither defined nor named by a planned section 10 row.

Usage: gen_make_docs.py [--root DIR] [--out-dir DIR] [--check]   (defaults: this repository, its docs/reference)
Exit:  0 written / clean; 1 findings (nothing is written while a `#:` finding is open); 2 an input cannot be read
       (no Makefile, no mk/*.mk, no target, no section 10 table, ROOT is not the top of a git work tree, no tracked
       public *.md) or the output cannot be written.
"""

import argparse
import difflib
import shutil
import subprocess
import sys
from pathlib import Path

from make_docs_model import Finding, Inventory, ModelError, collect, commands, gate_rows, table_findings

OUTPUT_DIR = Path("docs/reference")
OUTPUT = OUTPUT_DIR / "make-targets.md"
GATES = "ENGINEERING.md"
PRIVATE = ".team/"
REGENERATE = "python3 tools/codegen/gen_make_docs.py"
HEADER = f"""<!-- @generated by tools/codegen/gen_make_docs.py from Makefile and mk/*.mk - do not edit. -->
<!-- Regenerate: {REGENERATE}   (make check-make-docs fails while this file is stale) -->
<!-- SPDX-License-Identifier: Apache-2.0 -->
# Make targets

Every target that the top-level `Makefile` and its fragments `mk/*.mk` define, with the description from the
`#: <target> — <description>` line directly above its rule. `make test` runs the targets marked **yes**; the state
of each quality gate is the table in `ENGINEERING.md` section 10, and how to add a fragment is `mk/README.md`.
Regenerate this file with `{REGENERATE}`.

| Target | Description | In `make test` | Defined in |
|---|---|---|---|
"""


def render(inventory: Inventory) -> str:
    """The complete Markdown reference, targets sorted by name."""
    run = {name for name, _path, _line in inventory.entries}
    rows = []
    for name in sorted(inventory.targets):
        target = inventory.targets[name]
        in_test = "—" if name == "test" else "yes" if name in run else "no"
        text = target.description.replace("|", "\\|")
        rows.append(f"| `{name}` | {text} | {in_test} | `{target.path}` |\n")
    return HEADER + "".join(rows)


def _read(root: Path, relative: str) -> str:
    try:
        return (root / relative).read_text(encoding="utf-8")
    except (OSError, UnicodeDecodeError) as error:
        raise ModelError(f"{relative}: cannot read: {error}") from None


def make_files(root: Path) -> list[tuple[str, str]]:
    """(path, text) of the Makefile and every mk/*.mk in include order (raises ModelError on a missing input)."""
    fragments = sorted(path.relative_to(root).as_posix() for path in root.glob("mk/*.mk"))
    if not fragments:
        raise ModelError("mk/*.mk: no fragment found")
    return [(name, _read(root, name)) for name in ["Makefile", *fragments]]


def _git(root: Path, *args: str) -> str:
    exe = shutil.which("git")
    if exe is None:
        raise ModelError("git not found on PATH")
    try:
        done = subprocess.run([exe, "-C", str(root), *args], capture_output=True, text=True, check=False)  # noqa: S603 - fixed git argv
    except OSError as error:
        raise ModelError(f"git: cannot run: {error}") from None
    if done.returncode != 0:
        raise ModelError(f"git {' '.join(args)}: {done.stderr.strip() or done.returncode}")
    return done.stdout


def public_docs(root: Path) -> list[str]:
    """Tracked *.md outside the private team folder (raises ModelError when ROOT is no git top or none exist)."""
    top = Path(_git(root, "rev-parse", "--show-toplevel").strip())
    if top.resolve() != root.resolve():
        raise ModelError(f"{root}: not the top of a git work tree (top: {top})")
    names = [name for name in _git(root, "ls-files", "-z", "--", "*.md").split("\0") if name]
    public = sorted(name for name in names if not name.startswith(PRIVATE))
    if not public:
        raise ModelError("no tracked public *.md file")
    return public


def stale(out: Path, text: str) -> list[Finding]:
    """A finding when out is not the generated file; a unified diff on stdout when only its content differs."""
    shown = OUTPUT.as_posix()
    if out.is_symlink() or not out.is_file():
        return [Finding(shown, 1, f"is missing, a symlink or not a regular file; run: {REGENERATE}")]
    try:
        current = out.read_bytes()
    except OSError as error:
        raise ModelError(f"{shown}: cannot read: {error.strerror or error}") from None
    if current == text.encode("utf-8"):
        return []
    old = current.decode("utf-8", errors="replace").splitlines(keepends=True)
    sys.stdout.writelines(difflib.unified_diff(old, text.splitlines(keepends=True), shown, f"{shown} (generated)"))
    return [Finding(shown, 1, f"is stale (edited, or a `#:` line changed); run: {REGENERATE}")]


def doc_findings(root: Path, inventory: Inventory, planned: set[str]) -> list[Finding]:
    """`make <t>` in a public doc for a target that is neither defined nor planned in section 10 (the reference
    itself is generated from the targets and checked for freshness instead)."""
    findings = []
    for name in (doc for doc in public_docs(root) if doc != OUTPUT.as_posix()):
        for line, target in commands(_read(root, name)):
            if target not in inventory.targets and target not in planned:
                findings.append(Finding(name, line, f"`make {target}`: no rule defines it and no planned gate row"))
    return findings


def check(root: Path, out: Path, inventory: Inventory) -> list[Finding]:
    """Every finding of the gate over the tree under root."""
    rows, findings = gate_rows(_read(root, GATES), GATES)
    planned = {name for row in rows if row.state == "planned" for name in row.targets}
    findings = inventory.findings + findings + stale(out, render(inventory))
    findings += table_findings(inventory, rows, GATES)
    return findings + doc_findings(root, inventory, planned)


def run(root: Path, out: Path, check_only: bool) -> int:
    inventory = collect(make_files(root))
    if not inventory.targets:
        raise ModelError("Makefile, mk/*.mk: no target defined")
    findings = check(root, out, inventory) if check_only else inventory.findings
    for finding in findings:
        sys.stderr.write(f"{finding}\n")
    if findings:
        return 1
    if check_only:
        sys.stdout.write(f"check-make-docs: OK ({len(inventory.targets)} targets, {OUTPUT} fresh)\n")
        return 0
    try:
        out.parent.mkdir(parents=True, exist_ok=True)
        if out.is_symlink():
            out.unlink()
        out.write_text(render(inventory), encoding="utf-8")
    except OSError as error:
        raise ModelError(f"{error.filename or out}: cannot write: {error.strerror or error}") from None
    return 0


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description="Generate and check docs/reference/make-targets.md.")
    parser.add_argument("--root", type=Path, default=Path(__file__).resolve().parents[2])
    parser.add_argument("--out-dir", type=Path, help=f"directory of {OUTPUT.name} (default: <root>/{OUTPUT_DIR})")
    parser.add_argument("--check", action="store_true", help="check instead of writing (exit 1 on findings)")
    args = parser.parse_args(argv)
    try:
        return run(args.root, (args.out_dir or args.root / OUTPUT_DIR) / OUTPUT.name, args.check)
    except ModelError as error:
        sys.stderr.write(f"gen_make_docs: {error}\n")
        return 2


if __name__ == "__main__":
    sys.exit(main())
