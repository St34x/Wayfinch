"""Tests of tools/quality/check_size.py: planted files in throwaway git repos, run through main()."""

import importlib.util
import shutil
import subprocess
import sys
from pathlib import Path
from types import ModuleType

import pytest

QUALITY = Path(__file__).resolve().parents[1]
GIT = shutil.which("git") or "git"


def _load() -> ModuleType:
    spec = importlib.util.spec_from_file_location("check_size", QUALITY / "check_size.py")
    assert spec is not None and spec.loader is not None
    module = importlib.util.module_from_spec(spec)
    sys.modules["check_size"] = module
    spec.loader.exec_module(module)
    return module


cs = _load()


def lines(n: int, prefix: str = "x = 1") -> str:
    return "".join(f"{prefix}\n" for _ in range(n))


def py_func(name: str, length: int, indent: str = "") -> str:
    body = "".join(f"{indent}    v = {i}\n" for i in range(length - 1))
    return f"{indent}def {name}() -> None:\n{body}"


def sh_func(name: str, length: int) -> str:
    body = "".join(f"\techo {i}\n" for i in range(length - 2))
    return f"{name}() {{\n{body}}}\n"


def errors(out: str) -> list[str]:
    return [line for line in out.splitlines() if line.startswith("check-size: error")]


class Repo:
    def __init__(self, root: Path) -> None:
        self.root = root
        subprocess.run([GIT, "init", "-q", str(root)], check=True)
        self.exempt = "*.schema.json\n**/generated/**\n"
        self.baseline = ""

    def add(self, path: str, text: str, track: bool = True) -> None:
        target = self.root / path
        target.parent.mkdir(parents=True, exist_ok=True)
        target.write_text(text, encoding="utf-8")
        if track:
            subprocess.run([GIT, "-C", str(self.root), "add", path], check=True)

    def run(self, capsys: pytest.CaptureFixture[str]) -> tuple[int, str]:
        (self.root / "exempt.txt").write_text(self.exempt, encoding="utf-8")
        (self.root / "baseline.txt").write_text(self.baseline, encoding="utf-8")
        argv = ["--root", str(self.root), "--exempt", str(self.root / "exempt.txt")]
        rc = cs.main([*argv, "--baseline", str(self.root / "baseline.txt")])
        out = capsys.readouterr()
        return rc, out.out + out.err


