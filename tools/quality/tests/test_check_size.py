def test_sh_function_61_fails(repo: Repo, capsys: pytest.CaptureFixture[str]) -> None:
    repo.add("t.sh", "#!/bin/sh\nshort() { echo hi; }\n" + sh_func("ok", 60) + sh_func("too_long", 61))
    rc, out = repo.run(capsys)
    assert rc == 1
    assert any("t.sh::too_long" in e for e in errors(out))
    assert not any("::ok" in e or "short" in e for e in errors(out))


@pytest.mark.parametrize("gap", ["", "\n", "  # c\n"])
def test_sh_brace_on_the_next_line_is_measured(repo: Repo, capsys: pytest.CaptureFixture[str], gap: str) -> None:
    repo.add("t.sh", f"f()\n{gap}{{\n" + sh_func("x", 61).split("\n", 1)[1] + "g ()\n(\n\techo\n)\n")
    rc, out = repo.run(capsys)
    assert rc == 1 and any("t.sh::f" in e for e in errors(out)), out
    assert [name for name, _ in cs.sh_functions((repo.root / "t.sh").read_text(encoding="utf-8"))] == ["f", "g"]


def test_heredoc_brace_at_column_0_does_not_end_the_function(repo: Repo, capsys: pytest.CaptureFixture[str]) -> None:
    doc = "\tcat <<EOF\n{\n}\nEOF\n\tcat <<-'END' >x\n\t}\n\tEND\n"  # review probe: was measured 33
    body = "".join(f"\techo {i}\n" for i in range(28))
    repo.add("t.sh", "f() {\n" + body + doc + body + "}\n")
    rc, out = repo.run(capsys)
    assert rc == 1 and any("t.sh::f: 65 lines" in e for e in errors(out)), out


def test_heredoc_bodies_hold_no_functions(repo: Repo, capsys: pytest.CaptureFixture[str]) -> None:
    doc = "cat <<\\EOF\ng() {\n" + "x\n" * 70 + "}\nEOF\n"
