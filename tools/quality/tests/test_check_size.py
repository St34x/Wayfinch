        ("# @generated by tools/codegen\n", 0),
        ("#!/usr/bin/env python3\n# SPDX-License-Identifier: Apache-2.0\n\n# @generated by tools/codegen\n", 0),
        ("// SPDX-License-Identifier: Apache-2.0\n/*\n * @generated by tools/codegen\n */\n", 0),
