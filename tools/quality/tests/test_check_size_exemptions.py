"""Exemptions and edge cases of tools/quality/check_size.py.

Header-marker exemption per file type, here-document edge cases, the "never passes vacuously" property of the
here-document false positives, sh functions whose brace line also holds code, and the baseline block rules.
"""

import importlib.util
import shutil
import subprocess
import sys
from pathlib import Path
from types import ModuleType

import pytest

QUALITY = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(QUALITY))  # check_size.py imports size_sh.py from its own directory
GIT = shutil.which("git") or "git"


def _load() -> ModuleType:
    spec = importlib.util.spec_from_file_location("check_size_exemptions_mod", QUALITY / "check_size.py")
    assert spec is not None and spec.loader is not None
    module = importlib.util.module_from_spec(spec)
    sys.modules["check_size_exemptions_mod"] = module
    spec.loader.exec_module(module)
    return module


cs = _load()


def gen(n: int, line: str) -> str:
    return "".join(f"{line}\n" for _ in range(n))


def sh_body(n: int) -> str:
    return gen(n, "\techo x")


class Repo:
    def __init__(self, root: Path) -> None:
        self.root = root
        subprocess.run([GIT, "init", "-q", str(root)], check=True)
        self.baseline = ""
        self.add("ok.py", gen(10, "x = 1"))

    def add(self, path: str, text: str) -> None:
        target = self.root / path
        target.parent.mkdir(parents=True, exist_ok=True)
        target.write_bytes(text.encode("utf-8"))
        subprocess.run([GIT, "-C", str(self.root), "add", "--", path], check=True)

    def run(self, capsys: pytest.CaptureFixture[str]) -> tuple[int, str]:
        (self.root / "exempt.txt").write_text("", encoding="utf-8")
        (self.root / "baseline.txt").write_text(self.baseline, encoding="utf-8")
        argv = ["--root", str(self.root), "--exempt", str(self.root / "exempt.txt")]
        rc = cs.main([*argv, "--baseline", str(self.root / "baseline.txt")])
        out = capsys.readouterr()
        return rc, out.out + out.err


@pytest.fixture
def repo(tmp_path: Path) -> Repo:
    return Repo(tmp_path / "r")


# --- header marker: must exempt ---------------------------------------------------------------------------------


@pytest.mark.parametrize(
    ("path", "head"),
    [
        ("app/G.kt", "// @generated by tools/codegen\n"),
        ("app/G.kt", "/* @generated */\n"),
        ("app/G.kt", "/**\n * @generated by tools/codegen\n */\n"),
        ("app/G.kt", "// SPDX-License-Identifier: Apache-2.0\n//\n// @generated\n"),
        ("docs/g.md", "<!-- SPDX-License-Identifier: Apache-2.0 -->\n<!-- @generated -->\n"),
        ("t/g.sh", "#!/bin/sh\n# SPDX-License-Identifier: Apache-2.0\n# @generated by tools/codegen\n"),
        ("mk/g.mk", "# @generated\n"),
        ("g.py", "\n\n\n# @generated\n"),
        ("g.py", "#\n" * 9 + "# @generated\n"),
        ("g.py", "# SPDX-License-Identifier: Apache-2.0\r\n# @generated\r\n"),
        ("g.py", "\t# @generated\n"),
    ],
)
def test_header_marker_exempts(repo: Repo, capsys: pytest.CaptureFixture[str], path: str, head: str) -> None:
    repo.add(path, head + gen(900, "x = 1"))
    rc, out = repo.run(capsys)
    assert rc == 0 and path not in out, out


# --- header marker: must not exempt -----------------------------------------------------------------------------


@pytest.mark.parametrize(
    ("path", "head"),
    [
        ("app/G.kt", "package a\n// @generated\n"),
        ("app/G.kt", 'val s = "// @generated"\n'),
        ("app/G.kt", "// not @generated\n"),
        ("app/G.kt", "// @GENERATED\n"),
        ("docs/g.md", "Text first.\n<!-- @generated -->\n"),
        ("docs/g.md", "<!--\n@generated\n-->\n"),
        ("t/g.sh", "cat <<EOF\n# @generated\nEOF\n"),
        ("t/g.sh", "#!/bin/sh @generated\n"),
        ("g.py", "#\n" * 10 + "# @generated\n"),
        ("g.py", "# @generated-ish\n"),
    ],
)
def test_other_mentions_do_not_exempt(repo: Repo, capsys: pytest.CaptureFixture[str], path: str, head: str) -> None:
    repo.add(path, head + gen(900, "x = 1"))
    rc, out = repo.run(capsys)
    assert rc == 1 and path in out, out


# --- here-documents: measured to the real closing brace ---------------------------------------------------------


@pytest.mark.parametrize(
    ("opening", "skipped"),
    [
        ("\tcat <<-EOF\n", "\t}\n\tEOF\n"),
        ("\tcat <<'EOF'\n", "}\nEOF\n"),
        ('\tcat <<"EOF"\n', "}\nEOF\n"),
        ("\tcat <<\\EOF\n", "}\nEOF\n"),
        ("\tcat <<A <<B\n", "}\nA\n}\nB\n"),
        ("\tcat <<EOF\n", "}\nEOF \nEOF\n"),  # "EOF " is not the delimiter
    ],
)
def test_heredoc_forms_are_skipped(opening: str, skipped: str) -> None:
    text = "f() {\n" + opening + skipped + sh_body(60) + "}\n"
    assert cs.sh_functions(text) == [("f", text.count("\n"))]


@pytest.mark.parametrize("line", ["\t# see cat <<EOF\n", "\tcat <<<word\n", "\techo $((1 << 2))\n"])
def test_non_heredoc_shift_operators_are_not_heredocs(line: str) -> None:
    text = "f() {\n" + line + sh_body(60) + "}\n"
    assert cs.sh_functions(text) == [("f", 63)]


@pytest.mark.parametrize(
    "line",
    ["\techo x # <<EOF\n", "\techo $((x << y))\n", '\techo "<<EOF"\n', "\tcat <<END-X\n}\nEND-X\n"],
)
def test_heredoc_false_positives_never_pass(repo: Repo, capsys: pytest.CaptureFixture[str], line: str) -> None:
    repo.add("t.sh", "f() {\n" + line + sh_body(60) + "}\n")
    rc, out = repo.run(capsys)
    assert rc == 1 and "t.sh" in out, out


@pytest.mark.parametrize("header", ["f() { set -e\n", "f() { cat <<EOF\n}\nEOF\n"])
def test_code_on_the_brace_line_is_measured(repo: Repo, capsys: pytest.CaptureFixture[str], header: str) -> None:
    repo.add("t.sh", header + sh_body(60) + "}\n")
    rc, out = repo.run(capsys)
    assert rc == 1 and "t.sh::f" in out, out


@pytest.mark.parametrize(
    ("text", "expected"),
    [
        ("f() { set -e\n\techo x\n}\n", [("f", 3)]),
        ("f() { a; while x; do b\n\tc; done; return 1; }\n", [("f", 2)]),
        ("f() { echo ${x}\n\techo y; }\n", [("f", 2)]),
        ("f() { a # comment with }\n\tb; }\n", [("f", 2)]),
        ("f() { cat <<EOF\n}\nEOF\n\techo x\n}\n", [("f", 5)]),
        ("f() ( cd x\n\tls; )\n", [("f", 2)]),
        ('f() ( x=$(date)\n\techo "$x"\n)\n', [("f", 3)]),
        ("f()\n{ set -e\n\techo x; }\n", [("f", 3)]),
        ("f() { echo; }\ng() ( cd x; ls )\nh() { a=${x}; }\n", []),
        ('f() { a\n\t[ -n "$x" ] || { echo e; exit 1; }\n\tb\n}\n', [("f", 4)]),
        ("f() { a\n\t{\n\t\tb; }\n\tc; }\n", [("f", 4)]),
    ],
)
def test_code_on_the_brace_line_ends_at_the_matching_close(text: str, expected: list[tuple[str, int]]) -> None:
    assert cs.sh_functions(text) == expected


def test_code_on_the_brace_line_hard_limit_boundary(repo: Repo, capsys: pytest.CaptureFixture[str]) -> None:
    repo.add("t.sh", "f() { set -e\n" + sh_body(59) + "\techo; }\nok() { set -e\n" + sh_body(58) + "}\n")
    rc, out = repo.run(capsys)
    found = [line for line in out.splitlines() if "t.sh::" in line]
    assert rc == 1 and found[1:] == ["check-size: error: t.sh::f: 61 lines > hard limit 60"], out
    assert found[0] == "check-size: warning: t.sh::ok: 60 lines > target 40", out


def test_one_line_function_closed_before_a_redirection_is_not_measured(
    repo: Repo, capsys: pytest.CaptureFixture[str]
) -> None:
    repo.add("t.sh", "f() { echo; } >&2\n")
    rc, out = repo.run(capsys)
    assert rc == 0 and "t.sh::f" not in out and "error" not in out, out


# --- baseline block rules ---------------------------------------------------------------------------------------


@pytest.mark.parametrize(
    "text",
    [
        "# T1.110\n# note inside the block\nbig.py:450 # T1.110\n",
        "# T1.110 split the schema tests\nbig.py:450 # T1.110\n",
        "  # T1.110\nbig.py:450 # T1.110 split later\n",
        "# SPDX-License-Identifier: Apache-2.0\n# Entry: <path>:<lines> # T<id>\n\n# T1.06a\nbig.py:450 # T1.06a\n",
    ],
)
def test_baseline_block_forms_accepted(repo: Repo, capsys: pytest.CaptureFixture[str], text: str) -> None:
    repo.add("big.py", gen(450, "x = 1"))
    repo.baseline = text
    rc, out = repo.run(capsys)
    assert rc == 0, out


@pytest.mark.parametrize(
    "text",
    [
        "# T1.110\nother.py:450 # T1.110\n\nbig.py:450 # T1.110\n",  # blank line ended the block
        "# T1.110\nother.py:450 # T1.110\n   \nbig.py:450 # T1.110\n",  # whitespace-only line too
        "# notes\nbig.py:450 # T1.110\n",  # a non-id comment opens no block
        "# T1.06ab\nbig.py:450 # T1.06ab\n",  # two-letter suffix is not an id
        "# T1.06A\nbig.py:450 # T1.06A\n",
        "# T1.11\nbig.py:450 # T1.110\n",  # id prefix is not the block id
        "# T1.110\nbig.py:450 # T1.11\n",
    ],
)
def test_baseline_block_rule_violations_are_usage_errors(
    repo: Repo, capsys: pytest.CaptureFixture[str], text: str
) -> None:
    repo.add("big.py", gen(450, "x = 1"))
    (repo.root / "other.py").write_text(gen(450, "x = 1"), encoding="utf-8")
    repo.baseline = text
    rc, out = repo.run(capsys)
    assert rc == 2 and "baseline line" in out, out
